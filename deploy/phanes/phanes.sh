#!/usr/bin/env bash
# Deploy / redeploy / remove Phanes (the Control Center for Quant Trading Bot) on RedmiBook.
#
#   deploy/phanes/phanes.sh install      build and (re)deploy; keeps existing keys and config
#   deploy/phanes/phanes.sh uninstall    remove everything phanes put on this machine
#   deploy/phanes/phanes.sh reinstall    uninstall, then install (new Gnosis and Celestia keys!)
#
# Add --yes to skip the confirmation prompt of uninstall / reinstall.
# Run as your normal user from anywhere; sudo is used where needed.

set -euo pipefail

readonly BINARY=/usr/local/bin/phanes
readonly CONFIG_DIRECTORY=/etc/phanes
# A raw X25519 key, private or public, is the last 32 bytes of its DER encoding; a private key's DER is
# this PKCS#8 prefix followed by the raw key.
readonly X25519_KEY_BYTES=32
readonly X25519_PRIVATE_KEY_DER_PREFIX='\x30\x2e\x02\x01\x00\x30\x05\x06\x03\x2b\x65\x6e\x04\x22\x04\x20'
readonly CONFIG_FILE=$CONFIG_DIRECTORY/phanes.toml
readonly UNIT_FILE=/etc/systemd/system/phanes.service
REPOSITORY_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
readonly REPOSITORY_ROOT

log() { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*" >&2; }
die() { printf '\033[1;31mxx\033[0m %s\n' "$*" >&2; exit 1; }

confirm() {
    [[ ${ASSUME_YES:-false} == true ]] && return 0
    read -r -p "$1 [y/N] " answer
    [[ $answer == y || $answer == Y ]]
}

install_phanes() {
    cd "$REPOSITORY_ROOT"
    command -v cargo >/dev/null || die "cargo not found; install Rust via rustup first"
    command -v openssl >/dev/null || die "openssl not found; it generates Phanes' key pairs"

    log "building release binary"
    cargo build --release -p teyvat --bin phanes
    sudo install -m 755 target/release/phanes "$BINARY"

    log "preparing $CONFIG_DIRECTORY"
    sudo mkdir -p "$CONFIG_DIRECTORY"
    sudo chown -R "$USER:" "$CONFIG_DIRECTORY"
    chmod 700 "$CONFIG_DIRECTORY"

    [[ -f $CONFIG_FILE ]] || install -m 600 deploy/phanes/phanes.example.toml "$CONFIG_FILE"
    fill_private_key "<Gnosis private key, generated by the install>"
    fill_private_key "<Celestia private key, generated by the install>"

    log "installing systemd unit"
    sed "s/<your user>/$USER/" deploy/phanes/phanes.service | sudo tee "$UNIT_FILE" >/dev/null
    sudo systemctl daemon-reload
    sudo systemctl enable --quiet phanes

    local missing=()
    grep -q '<Osaka IP' "$CONFIG_FILE" && missing+=("Osaka's IPv4 in [clients.Osaka] of $CONFIG_FILE, and its IPv6 (or delete that optional line)")
    grep -q '<base64' "$CONFIG_FILE" && missing+=("each client's client_gnosis_service_public_key / client_celestia_service_public_key in $CONFIG_FILE")
    grep -q '<API ' "$CONFIG_FILE" && missing+=("the keys in the [gnoses.<gnosis_id>] tables of $CONFIG_FILE")
    grep -q '<fill me' "$CONFIG_FILE" && missing+=("[bark] credentials in $CONFIG_FILE")
    if ((${#missing[@]} > 0)); then
        warn "not starting yet; fill in:"
        printf '     - %s\n' "${missing[@]}" >&2
        warn "then run: sudo systemctl restart phanes"
        print_public_keys
        return 0
    fi

    log "restarting phanes"
    sudo systemctl restart phanes
    check_health
    print_public_keys
}

check_health() {
    local address
    address=$(sed -n 's/^listen_address *= *"\(.*\)".*/\1/p' "$CONFIG_FILE")
    for _ in $(seq 10); do
        if curl -fsS "http://$address/info" >/dev/null 2>&1; then
            log "phanes is healthy on $address"
            return 0
        fi
        sleep 1
    done
    sudo systemctl status phanes --no-pager || true
    die "phanes did not become healthy; see: journalctl --namespace=phanes -u phanes -e"
}

# Fills the placeholder $1 of the config with a fresh X25519 private key in base64. A filled-in key is
# left alone, so redeploys keep the key. The key only passes through pipes and bash variables, never a
# file or a command line, and its public half is never stored: public_key_of derives it when needed.
fill_private_key() {
    local placeholder=$1 private_key config_text
    grep -qF "$placeholder" "$CONFIG_FILE" || return 0
    log "generating $placeholder"
    private_key=$(openssl genpkey -algorithm X25519 -outform DER | tail -c "$X25519_KEY_BYTES" | base64)
    [[ -n $private_key ]] || die "openssl did not produce a private key"
    config_text=$(<"$CONFIG_FILE")
    printf '%s\n' "${config_text//"$placeholder"/"$private_key"}" >"$CONFIG_FILE"
}

# The base64 public key of the base64 private key in field $1 of the config, as Noise derives it.
public_key_of() {
    local private_key
    private_key=$(sed -n "s/^$1 *= *\"\([^\"]*\)\".*/\1/p" "$CONFIG_FILE")
    { printf '%b' "$X25519_PRIVATE_KEY_DER_PREFIX"; printf '%s' "$private_key" | base64 -d; } \
        | openssl pkey -inform DER -pubout -outform DER | tail -c "$X25519_KEY_BYTES" | base64
}

print_public_keys() {
    log "give these to every client:"
    log "  Gnosis public key:   $(public_key_of gnosis_private_key)"
    log "  Celestia public key: $(public_key_of celestia_private_key)"
}

uninstall_phanes() {
    warn "this deletes $CONFIG_DIRECTORY (Gnosis and Celestia keys, config incl. the gnoses and Bark credentials),"
    warn "$BINARY, $UNIT_FILE and the phanes journal logs."
    warn "Every client will need the new Gnosis and Celestia public keys after a reinstall."
    confirm "continue?" || die "aborted"

    if systemctl list-unit-files phanes.service >/dev/null 2>&1; then
        log "stopping and disabling phanes"
        sudo systemctl disable --now phanes >/dev/null 2>&1 || true
    fi
    sudo rm -f "$UNIT_FILE"
    sudo systemctl daemon-reload
    sudo systemctl reset-failed phanes >/dev/null 2>&1 || true
    sudo rm -f "$BINARY"
    sudo rm -rf "$CONFIG_DIRECTORY"

    log "deleting phanes journal logs"
    sudo systemctl stop systemd-journald@phanes.service systemd-journald@phanes.socket \
        systemd-journald-varlink@phanes.socket >/dev/null 2>&1 || true
    sudo sh -c 'rm -rf /var/log/journal/*.phanes /run/log/journal/*.phanes'
    log "phanes removed (the cloudflared hostname is left untouched)"
}

main() {
    [[ $EUID -ne 0 ]] || die "run as your normal user, not root"
    local command=${1:-}
    [[ ${2:-} == --yes ]] && ASSUME_YES=true
    case $command in
        install) install_phanes ;;
        uninstall) uninstall_phanes ;;
        reinstall) uninstall_phanes && install_phanes ;;
        *) die "usage: $0 install|uninstall|reinstall [--yes]" ;;
    esac
}

main "$@"
