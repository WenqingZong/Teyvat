#!/usr/bin/env bash
# Deploy / redeploy / remove the Market Data Provider on the trading host (Osaka).
#
#   deploy/market_data_provider/market_data_provider.sh install      build and (re)deploy; keeps the existing key and config
#   deploy/market_data_provider/market_data_provider.sh uninstall    remove everything the provider put on this machine
#   deploy/market_data_provider/market_data_provider.sh reinstall    uninstall, then install (new Gnosis client key!)
#
# Add --yes to skip the confirmation prompt of uninstall / reinstall.
# Run as the user the strategies run as, from anywhere; sudo is used where needed.

set -euo pipefail

readonly SERVICE=market_data_provider
readonly BINARY=/usr/local/bin/market_data_provider
readonly CONFIG_DIRECTORY=/etc/market_data_provider
# A raw X25519 key, private or public, is the last 32 bytes of its DER encoding; a private key's DER is
# this PKCS#8 prefix followed by the raw key.
readonly X25519_KEY_BYTES=32
readonly X25519_PRIVATE_KEY_DER_PREFIX='\x30\x2e\x02\x01\x00\x30\x05\x06\x03\x2b\x65\x6e\x04\x22\x04\x20'
readonly CONFIG_FILE=$CONFIG_DIRECTORY/market_data_provider.toml
readonly UNIT_FILE=/etc/systemd/system/$SERVICE.service
# DEFAULT_ROOT_DIRECTORY: one ring file per topic, read by the strategies.
readonly RING_DIRECTORY=/dev/shm/market_data_provider
REPOSITORY_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
readonly REPOSITORY_ROOT

log() { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*" >&2; }
die() { printf '\033[1;31mxx\033[0m %s\n' "$*" >&2; exit 1; }

confirm() {
    [[ ${ASSUME_YES:-false} == true ]] && return 0
    read -r -p "$1 [y/N] " answer
    [[ $answer == y || $answer == Y ]]
}

install_provider() {
    cd "$REPOSITORY_ROOT"
    command -v cargo >/dev/null || die "cargo not found; install Rust via rustup first"
    command -v openssl >/dev/null || die "openssl not found; it generates the Gnosis client key"

    log "building release binary"
    cargo build --release -p teyvat --bin market_data_provider
    # Install beside, then rename: overwriting the running binary in place fails with "Text file busy".
    sudo install -m 755 target/release/market_data_provider "$BINARY.new"
    sudo mv "$BINARY.new" "$BINARY"

    log "preparing $CONFIG_DIRECTORY"
    sudo mkdir -p "$CONFIG_DIRECTORY"
    sudo chown -R "$USER:" "$CONFIG_DIRECTORY"
    chmod 700 "$CONFIG_DIRECTORY"

    [[ -f $CONFIG_FILE ]] || install -m 600 deploy/market_data_provider/market_data_provider.example.toml "$CONFIG_FILE"
    fill_private_key "<Gnosis client private key, generated by the install>"

    # systemd-logind deletes a user's /dev/shm files once their last session ends (RemoveIPC=yes), which
    # would pull the rings from under running strategies; a lingering user never fully logs out.
    log "enabling linger for $USER so logging out keeps the rings"
    sudo loginctl enable-linger "$USER"

    log "installing systemd unit"
    sed "s/<your user>/$USER/" deploy/$SERVICE/$SERVICE.service | sudo tee "$UNIT_FILE" >/dev/null
    sudo systemctl daemon-reload
    sudo systemctl enable --quiet "$SERVICE"

    local missing=()
    grep -q '<Phanes URL' "$CONFIG_FILE" && missing+=("[phanes_client] url in $CONFIG_FILE")
    grep -q '<base64' "$CONFIG_FILE" && missing+=("[phanes_client] phanes_gnosis_public_key (printed by deploy/phanes/phanes.sh install on the Phanes host) in $CONFIG_FILE")
    grep -q '<fill me' "$CONFIG_FILE" && missing+=("[bark] credentials in $CONFIG_FILE")
    grep -q '^demo *=' "$CONFIG_FILE" || missing+=("demo = true|false in $CONFIG_FILE (see deploy/market_data_provider/market_data_provider.example.toml)")
    if ((${#missing[@]} > 0)); then
        warn "not starting yet; fill in:"
        printf '     - %s\n' "${missing[@]}" >&2
        warn "then run: sudo systemctl restart $SERVICE"
        print_phanes_instructions
        return 0
    fi

    log "restarting $SERVICE"
    sudo systemctl restart "$SERVICE"
    check_health
    print_phanes_instructions
}

check_health() {
    local port
    port=$(sed -n 's/^port *= *\([0-9]*\).*/\1/p' "$CONFIG_FILE")
    for _ in $(seq 10); do
        if curl -fsS "http://127.0.0.1:$port/health" >/dev/null 2>&1; then
            log "$SERVICE is healthy on 127.0.0.1:$port: $(curl -fsS "http://127.0.0.1:$port/info")"
            return 0
        fi
        sleep 1
    done
    sudo systemctl status "$SERVICE" --no-pager || true
    die "$SERVICE did not become healthy; see: journalctl --namespace=$SERVICE -u $SERVICE -e"
}

# Fills the placeholder $1 of the config with a fresh X25519 private key in base64. A filled-in key is
# left alone, so redeploys keep the key. The key only passes through pipes and bash variables, never a
# file or a command line, and its public half is never stored: public_key_of derives it when needed.
fill_private_key() {
    local placeholder=$1 private_key config_text
    grep -qF "$placeholder" "$CONFIG_FILE" || return 0
    log "generating $placeholder"
    private_key=$(openssl genpkey -algorithm X25519 -outform DER | tail -c "$X25519_KEY_BYTES" | base64)
    [[ -n $private_key ]] || die "openssl did not produce a private key"
    config_text=$(<"$CONFIG_FILE")
    printf '%s\n' "${config_text//"$placeholder"/"$private_key"}" >"$CONFIG_FILE"
}

# The base64 public key of the base64 private key in field $1 of the config, as Noise derives it.
public_key_of() {
    local private_key
    private_key=$(sed -n "s/^$1 *= *\"\([^\"]*\)\".*/\1/p" "$CONFIG_FILE")
    { printf '%b' "$X25519_PRIVATE_KEY_DER_PREFIX"; printf '%s' "$private_key" | base64 -d; } \
        | openssl pkey -inform DER -pubout -outform DER | tail -c "$X25519_KEY_BYTES" | base64
}

print_phanes_instructions() {
    log "on the Phanes host, in this machine's [clients.<name>] table of /etc/phanes/phanes.toml:"
    log "  client_gnosis_service_public_key = \"$(public_key_of client_gnosis_private_key)\""
    log "  allowed_gnosis_ids must include binance_sbe_real (live) or binance_sbe_demo (demo)"
    log "  then: sudo systemctl restart phanes"
}

uninstall_provider() {
    warn "this deletes $CONFIG_DIRECTORY (Gnosis client key, config incl. Bark credentials), $BINARY,"
    warn "$UNIT_FILE, the $SERVICE journal logs and the rings in $RING_DIRECTORY;"
    warn "stop every strategy first. Phanes will need the new Gnosis client public key after a reinstall."
    confirm "continue?" || die "aborted"

    if systemctl list-unit-files "$SERVICE.service" >/dev/null 2>&1; then
        log "stopping and disabling $SERVICE"
        sudo systemctl disable --now "$SERVICE" >/dev/null 2>&1 || true
    fi
    sudo rm -f "$UNIT_FILE"
    sudo systemctl daemon-reload
    sudo systemctl reset-failed "$SERVICE" >/dev/null 2>&1 || true
    sudo rm -f "$BINARY" "$BINARY.new"
    sudo rm -rf "$CONFIG_DIRECTORY" "$RING_DIRECTORY"

    log "deleting $SERVICE journal logs"
    sudo systemctl stop "systemd-journald@$SERVICE.service" "systemd-journald@$SERVICE.socket" \
        "systemd-journald-varlink@$SERVICE.socket" >/dev/null 2>&1 || true
    sudo sh -c "rm -rf /var/log/journal/*.$SERVICE /run/log/journal/*.$SERVICE"
    log "$SERVICE removed (linger for $USER is left on; disable it with: sudo loginctl disable-linger $USER)"
}

main() {
    [[ $EUID -ne 0 ]] || die "run as the strategies' user, not root"
    local command=${1:-}
    [[ ${2:-} == --yes ]] && ASSUME_YES=true
    case $command in
        install) install_provider ;;
        uninstall) uninstall_provider ;;
        reinstall) uninstall_provider && install_provider ;;
        *) die "usage: $0 install|uninstall|reinstall [--yes]" ;;
    esac
}

main "$@"
